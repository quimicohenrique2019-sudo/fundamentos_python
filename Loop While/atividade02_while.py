tabuada = 2
i = 1

while i <= 10:                                 # i=1     # i=2     # i=3
    print(f'{tabuada} x {i} = {tabuada*i}')    # 2x1=2   # 2x2=4   # 2x3=6
    i = i+1                                    # 1+1=2   # 2+1=3   # 3+1=4
   #(i+=1) = (i=i+1)